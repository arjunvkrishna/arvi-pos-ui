// Permanent safety check for the split frontend (run it before every release; the release checks do).
//   node tools/check-chunks.js          verify
//   node tools/check-chunks.js --write  regenerate the registry block in app.js, then verify
//
// How the split works: app.js is the always-loaded core. js/<name>.js files are loaded on first use. The core registers a
// stub for every function declared in a chunk (the REGISTRY block in app.js), so calls such as onclick="saveSupplier()" or
// switchTab() -> loadSuppliersData() load the chunk first and then run the real function.
// The rules below keep that safe.
const fs = require('fs'), path = require('path');
const acorn = require('acorn'), escope = require('eslint-scope');
const root = path.join(__dirname, '..');
const BEGIN = '// BEGIN LAZY REGISTRY (generated by tools/check-chunks.js --write; do not edit by hand)';
const END = '// END LAZY REGISTRY';
const write = process.argv.includes('--write');

const parse = (file) => { const src = fs.readFileSync(file, 'utf8'); return { src, ast: acorn.parse(src, { ecmaVersion: 2022, sourceType: 'script', locations: true, ranges: true }) }; };
const topLevel = (ast) => {
  const fns = [], vars = [], loadTime = [];
  for (const st of ast.body) {
    if (st.type === 'FunctionDeclaration') fns.push(st.id.name);
    else if (st.type === 'VariableDeclaration') for (const d of st.declarations) { if (d.id.type === 'Identifier') vars.push(d.id.name); else loadTime.push(`destructuring declaration at line ${st.loc.start.line}`); if (d.init && ['CallExpression', 'NewExpression', 'AwaitExpression'].includes(d.init.type)) loadTime.push(`initialiser runs at load, line ${st.loc.start.line}`); }
    else loadTime.push(`${st.type} at line ${st.loc.start.line}`);
  }
  return { fns, vars, loadTime };
};

const jsDir = path.join(root, 'js');
const chunkFiles = fs.existsSync(jsDir) ? fs.readdirSync(jsDir).filter(f => f.endsWith('.js')).sort() : [];
const coreFile = path.join(root, 'app.js');
const core = parse(coreFile);
const coreTop = topLevel(core.ast);
const chunks = {};
for (const f of chunkFiles) { const name = f.replace(/\.js$/, ''); const p = parse(path.join(jsDir, f)); chunks[name] = { ...p, top: topLevel(p.ast), file: f }; }

// ---- registry block
const registry = {}; for (const [n, c] of Object.entries(chunks)) registry[n] = [...c.top.fns].sort();
const block = BEGIN + '\nconst LAZY_REGISTRY = {\n' + Object.entries(registry).map(([n, fns]) => `  ${n}: [\n${fns.reduce((acc, fn, i) => { const line = acc.length ? acc[acc.length - 1] : ''; if (!acc.length || (line + `'${fn}', `).length > 112) acc.push(`    '${fn}', `); else acc[acc.length - 1] += `'${fn}', `; return acc; }, []).map(l => l.replace(/ $/, '')).join('\n')}\n  ],`).join('\n') + '\n};\n' + END;
let coreSrc = core.src;
const hasBlock = coreSrc.includes(BEGIN) && coreSrc.includes(END);
if (write) {
  if (!hasBlock) { console.error('app.js has no registry block markers'); process.exit(2); }
  const a = coreSrc.indexOf(BEGIN), b = coreSrc.indexOf(END) + END.length;
  fs.writeFileSync(coreFile, coreSrc.slice(0, a) + block + coreSrc.slice(b));
  console.log('registry block rewritten in app.js:', Object.entries(registry).map(([n, f]) => `${n}=${f.length}`).join(' '));
  process.exit(0);
}

let problems = [];
const current = hasBlock ? coreSrc.slice(coreSrc.indexOf(BEGIN), coreSrc.indexOf(END) + END.length) : '';
if (current !== block) problems.push('REGISTRY out of date: a function was added/removed/renamed in a js/*.js chunk. Run: node tools/check-chunks.js --write');

// ---- rule 1: no name declared twice across files (the later-loaded one would silently win)
const owner = new Map(); const dupes = [];
const note = (name, where) => { if (owner.has(name)) dupes.push(`${name} (${owner.get(name)} and ${where})`); else owner.set(name, where); };
coreTop.fns.concat(coreTop.vars).forEach(n => note(n, 'app.js')); for (const [n, c] of Object.entries(chunks)) c.top.fns.concat(c.top.vars).forEach(x => note(x, c.file));
if (dupes.length) problems.push('Declared in more than one file: ' + dupes.join(', '));

// ---- rule 2: a chunk may not read or write another chunk's variables; core variables are fine. Functions of other chunks are
// fine only through the registry (stubs), which covers every chunk function.
const all = new Map(); // name -> {file, kind}
coreTop.fns.forEach(n => all.set(n, { file: 'app.js', kind: 'fn' })); coreTop.vars.forEach(n => all.set(n, { file: 'app.js', kind: 'var' }));
for (const c of Object.values(chunks)) { c.top.fns.forEach(n => all.set(n, { file: c.file, kind: 'fn' })); c.top.vars.forEach(n => all.set(n, { file: c.file, kind: 'var' })); }
const refsOf = (f) => { const sm = escope.analyze(f.ast, { ecmaVersion: 2022, sourceType: 'script' }); const names = new Map(); for (const r of sm.globalScope.through) { const n = r.identifier.name; if (!names.has(n)) names.set(n, r.identifier.loc.start.line); } for (const v of sm.globalScope.variables) for (const r of v.references) if (!names.has(v.name)) names.set(v.name, r.identifier.loc.start.line); return names; };
const files = [{ name: 'app.js', ...core }, ...Object.values(chunks).map(c => ({ name: c.file, ...c }))];
for (const f of files) for (const [n, line] of refsOf(f)) {
  const d = all.get(n); if (!d || d.file === f.name) continue;
  if (d.kind === 'var' && d.file !== 'app.js') problems.push(`${f.name}:${line} uses variable "${n}" declared in ${d.file}. Shared state must be declared in app.js.`);
}
// ---- rule 3: chunks run when first loaded, not at page start, so they must contain only declarations
for (const c of Object.values(chunks)) for (const t of c.top.loadTime) problems.push(`${c.file}: code that runs at load: ${t}. Chunks may only declare functions and variables; move start-up code into app.js.`);
// ---- rule 4: html handlers must resolve to something that exists
const known = new Set([...all.keys()]);
const missing = new Set();
for (const f of ['index.html', 'menu.html']) { const html = fs.readFileSync(path.join(root, f), 'utf8'); const inline = new Set([...html.matchAll(/function\s+([A-Za-z_$][\w$]*)\s*\(/g)].map(m => m[1]));
  for (const m of html.matchAll(/\son(?:click|input|change|submit|keydown|keyup|blur|focus)="([^"]*)"/g)) for (const n of m[1].matchAll(/(?<![.\w$'"])([A-Za-z_$][\w$]*)\s*\(/g)) { const name = n[1]; if (!known.has(name) && !inline.has(name) && !/^(if|for|while|switch|return|function|event|this|Number|String|Math|parseInt|parseFloat|Boolean|Object|Array|JSON|Date|confirm|alert|prompt|setTimeout|clearTimeout|history|window|document|navigator|location|localStorage|sessionStorage|encodeURIComponent|decodeURIComponent|isNaN|Event|CustomEvent|URL)$/.test(name)) missing.add(f + ': ' + name); } }
if (missing.size) problems.push('HTML handlers calling functions that are not declared anywhere: ' + [...missing].slice(0, 12).join(', '));

const total = chunkFiles.reduce((a, f) => a + fs.statSync(path.join(jsDir, f)).size, 0);
console.log(`core app.js ${(fs.statSync(coreFile).size / 1024).toFixed(0)} KB; ${chunkFiles.length} chunks, ${(total / 1024).toFixed(0)} KB total: ` + Object.entries(chunks).map(([n, c]) => `${n}(${c.top.fns.length} fn)`).join(' '));
if (problems.length) { console.error('\nCHECK FAILED:\n - ' + problems.join('\n - ')); process.exit(1); }
console.log('OK: registry current, no duplicate declarations, no cross-chunk variable use, chunks declaration-only, HTML handlers resolve.');
